_TRUNCATED_MARK = "[TRUNCATED — unsummarized, full text in {ref}]"

def _placeholder(material: str, limit: int, full_ref: str) -> str:
    """Fallback ENTRY text when summarization is unavailable (issue #9):
    keep the head AND the tail of `material` with an explicit marker
    pointing at the full text — never the old silent material[:limit]
    head-truncation that kept 2.6% and destroyed the newest material."""
    mark = _TRUNCATED_MARK.format(ref=full_ref)
    if len(material) + len(mark) + 1 <= limit:
        return f"{mark} {material}"
    room = limit - len(mark) - 2      # one separator on each side of mark
    if room <= 0:
        return mark
    head = room // 2
    tail = room - head
    return f"{material[:head]} {mark} {material[-tail:]}"

async def _summarize(material: str, limit: int, gen_fn) -> str:
    """gen_fn(prompt) -> str. RAISES when generation is unavailable or
    returns nothing — the caller has already persisted `material`
    verbatim and turns the failure into a head+tail placeholder pointing
    at that raw file (issue #9: the old `return material[:limit]` here
    silently destroyed all but an ancient 2.6% sliver)."""
    out = await gen_fn(_SUMMARY_PROMPT.format(material=material,
                                              limit=limit))
    out = (out or "").strip()
    if not out:
        raise RuntimeError("summary generation returned empty output")
    return out


async def _store_conclusions(workspace: str, parsed: list[dict], era: str,
                             raw_ref: str, embed_fn) -> dict:
    """R76: persist the derived conclusions (append-only JSONL) with
    embeddings when the embed fn works — WITHOUT the embedding field when
    it raises (degraded, counted). Never raises: the conclusions side is
    best-effort and must never fail a compaction."""
    from . import conclusions as _store
    if not parsed:
        return {"conclusions": 0, "conclusions_unembedded": 0}
    raw_premise = ("raw/" + os.path.basename(raw_ref)) if raw_ref else None
    texts = [c["text"] for c in parsed]
    ts = datetime.now(timezone.utc).isoformat()   # one moment per pass
    vecs = None
    if embed_fn is not None:
        try:
            vecs = await embed_fn(texts)
            if len(vecs) != len(texts):
                raise RuntimeError(
                    f"embedding count mismatch ({len(vecs)} != {len(texts)})")
        except Exception as e:  # noqa: BLE001 — degraded, never broken
            print(f"[qtree] conclusion embedding failed ({e}); "
                  f"storing {len(texts)} unembedded", file=sys.stderr)
            vecs = None
    recs = []
    for c, v in zip(parsed, vecs if vecs is not None
                    else [None] * len(parsed)):
        premises = list(c["premises"])
        if raw_premise and raw_premise not in premises:
            premises.append(raw_premise)   # ground-truth source pointer
        recs.append(_store.make_record(
            text=c["text"], kind=c["kind"], era=era, premises=premises,
            ts=ts, embedding=v))
    _store.append_records(workspace, recs)
    return {"conclusions": len(recs),
            "conclusions_unembedded":
                0 if vecs is not None else len(recs)}


async def record_compaction(workspace: str, dropped: list[dict],
                            gen_fn, embed_fn=None) -> dict:
    """Called after a turn when `dropped` messages left the context.
    Summarizes them into a fresh L0 entry, then rolls up while a level
    holds 4 UNROLLED entries (children are kept on disk — the quadtree
    never loses fine detail, the pointer just advances).

    Issue #9: `dropped` is persisted VERBATIM to memory/qtree/raw/
    before summarizing. If summarization fails, a head+tail placeholder
    pointing at that raw file is written and the error RE-RAISED — the
    caller (maybe_compact) then leaves the live context untouched and
    the next turn retries compaction. A provider blip must never
    destroy material.

    R76: the SAME generation pass also derives conclusions (two-output
    prompt) which land in memory/conclusions.jsonl — embedded via the
    proxy when `embed_fn` works, stored without vectors when it does not.
    The conclusions side is wrapped so it can NEVER fail the compaction."""
    if not dropped:
        return {"entries": 0}
    material = "\n".join(
        f"[{m.get('role')}] {m.get('content') or ''}" for m in dropped)
    stamp = _now().strftime("%Y-%m-%d %H:%M")
    entry_budget = COMPACT_ENTRY_MAX - len(f"- [{stamp}] ")  # line_for head
    raw_ref = _save_raw(workspace, material)
    meta = load_meta(workspace)
    try:
        out = await _summarize(material, COMPACT_ENTRY_MAX, gen_fn)
    except Exception as e:  # noqa: BLE001 — memory must never break the loop
        print(f"[qtree] summarize failed ({e}); raw kept in {raw_ref}",
              file=sys.stderr)
        _append_entry(workspace, 0, line_for(
            _placeholder(material, entry_budget, raw_ref), stamp))
        _lvl(meta, 0)["entries"] += 1
        _save_meta(workspace, meta)
        raise     # issue #9: caller must NOT drop the messages
    summary, parsed = parse_generation(out)
    line = line_for(summary, stamp)
    _append_entry(workspace, 0, line)

    _lvl(meta, 0)["entries"] += 1
    try:
        concl_stats = await _store_conclusions(
            workspace, parsed, f"L0:{_lvl(meta, 0)['entries']}", raw_ref,
            embed_fn)
    except Exception as e:  # noqa: BLE001 — conclusions never fail compaction
        print(f"[qtree] conclusions side failed ({e}); summary kept",
              file=sys.stderr)
        concl_stats = {"conclusions": 0, "conclusions_unembedded": 0}
    rolled = 0
    level = 0
    while _unrolled(workspace, meta, level) >= COMPACT_FANOUT:
        entries = read_entries(workspace, level)
        m = _lvl(meta, level)
        four = entries[m["rolled"]:m["rolled"] + COMPACT_FANOUT]
        up = "\n".join(four)
        up_ref = _save_raw(workspace, up, suffix=f"-roll-L{level}")
        try:
            up_out = await _summarize(up, COMPACT_ENTRY_MAX, gen_fn)
            # rollups summarize ALREADY-derived entries: strip any
            # conclusions section from the entry (derivation happens once,
            # on the compaction pass)
            summary, _ = parse_generation(up_out)
        except Exception as e:  # noqa: BLE001 — the L0 entry is already
            # written (partially succeeded): the rollup entry must still
            # exist, so keep head+tail with the raw pointer (issue #9)
            # and continue — never a silent head-truncation.
            print(f"[qtree] rollup failed ({e}); raw kept in {up_ref}",
                  file=sys.stderr)
            summary = _placeholder(up, entry_budget, up_ref)
        _append_entry(workspace, level + 1, line_for(summary, stamp))
        _lvl(meta, level + 1)["entries"] += 1
        m["rolled"] += COMPACT_FANOUT
        rolled += 1
        level += 1
    _save_meta(workspace, meta)
    return {"entries": 1, "rolled": rolled, **concl_stats}


def line_for(summary: str, stamp: str) -> str:
    return f"- [{stamp}] {summary}".replace("\n", " ")[:COMPACT_ENTRY_MAX]


def context_block(workspace: str, budget: int = 200_000) -> str:
    """The always-in-context view (R75 — lifetime coverage): EVERY unrolled
    entry of every level, fine→coarse, oldest first within a level.
    Unrolled = entries written at the level minus meta[level].rolled (the
    rollup pointer). The unrolled sets across levels partition the agent's
    whole compacted life (base-4 digits shape): gapless coverage of all
    time with ≤3 entries per level by fanout-4 construction (and 0 at a
    level right after a rollup) — do NOT cap further.

    Default budget 200_000 chars (~50k tokens ≈ 16 levels × 3 × 4000) is a
    DESIGN DECISION implementing the ruling's context-window clause: the
    covered time per level grows quadratically while the gapless memory
    only grows linearly, so the default must never silently defeat the
    ruling. The trim stays for explicit small budgets (tests use it): it
    drops the COARSEST material first (fine→coarse order, coarsest level
    at the end), shedding a level's OLDEST unrolled entries before its
    newest (the newest is kept longest), and the newest L0 entry is the
    last thing to go — it is never dropped while more than one line
    remains (issue #5)."""
    meta = load_meta(workspace)
    if not meta:
        return ""
    lines: list[str] = []
    per_level: list[list[int]] = []   # line indices per level (fine→coarse)
    for level in sorted(int(k) for k in meta):
        entries = read_entries(workspace, level)
        rolled = _lvl(meta, level).get("rolled", 0)
        start = len(lines)
        for entry in entries[rolled:]:        # unrolled tail, oldest first
            body = re.sub(r"^- \[[^\]]+\] ", "", entry)
            # an L(n) entry summarizes 4^n L0 compactions (fanout 4)
            tag = ("recent" if level == 0
                   else f"~{4 ** level} compactions ago")
            lines.append(f"[{tag}] {body}")
        if len(lines) > start:
            per_level.append(list(range(start, len(lines))))
    text = "\n".join(lines)
    if len(text) > budget:
        # Drop order = least valuable first: the COARSEST level's OLDEST
        # unrolled entry first (keep its newest longest), then that level's
        # newest, then the next coarsest level … down to L0 whose newest
        # entry survives everything. One line always remains (it may
        # exceed a tiny budget alone).
        drop_order = [i for grp in reversed(per_level) for i in grp]
        keep = set(range(len(lines)))
        size = len(text)                    # = sum(len) + (n-1) join chars
        for i in drop_order:
            if len(keep) <= 1:
                break
            keep.discard(i)
            size -= len(lines[i]) + 1       # the line + its join newline
            if size <= budget:
                break
        text = "\n".join(line for j, line in enumerate(lines) if j in keep)
    return text


def needs_compaction(messages: list[dict], last_prompt_tokens: int | None = None,
                     context_window: int | None = None) -> bool:
    """True when the chatlog needs compacting (Felix R78):

    - token trigger: the last generation's provider-reported
      usage.prompt_tokens EXCEEDS 50% of the model's context window
      (strictly greater-than; the exact count is the signal — never an
      estimate); or
    - backstop: the non-system message COUNT reaches COMPACT_TRIGGER_MSGS
      (no usage data yet / failure storm). Kept only as a guard — it must
      fire BEFORE _sanitize's 2500-message tail-cap so information never
      silently leaves the context.

    The old char trigger (R70/R73) is RETIRED: chars are a proxy whose
    token density varies with language and content; a 10M-char log of
    tiny tokens is not over budget and must NOT compact."""
    if (last_prompt_tokens and context_window
            and last_prompt_tokens
            > COMPACT_TRIGGER_WINDOW_FRACTION * context_window):
        return True
    non_sys = [m for m in messages if m.get("role") != "system"]
    return len(non_sys) >= COMPACT_TRIGGER_MSGS
