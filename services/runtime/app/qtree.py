"""Fractal quadtree episodic memory (Felix's design, R70).

Every completed turn's _sanitize-drop list (the messages compacted out of
the live context) is summarized into a ≤COMPACT_ENTRY_MAX-char entry at
level 0 of `memory/qtree/L0.md`. Whenever a level has 4 NEW unrolled
entries, those four are summarized into ONE new entry (≤4000 chars)
appended to the level above; new levels are created as needed (no level
limit). Children are NEVER deleted — a level file is the complete
fine-grained log of its era (browsable via ws.read), the level above is
the coarser digest. The agent's system prompt always carries every
UNROLLED entry of EVERY level (R75 — lifetime coverage): the unrolled
tails across levels partition the whole compacted life (base-4 digits
shape), so a few summaries per level (≤3, 0 right after a rollup) give
gapless coverage of all time — fine recent history and coarse ancient
history at the same time.

Summaries are generated by the same metered provider stack as normal
turns (proxy /v1/jobs, class "task" — auxiliary, never agent-class
billing), single-shot, no tools. All state is plain markdown files in the
workspace, so an operator (or the agent) can read and edit the whole
tree by hand.

Layout:
  memory/qtree/L0.md   entries:  "- [2026-10-08 18:20] <summary>" (append-only)
  memory/qtree/L1.md   …         newest last
  memory/qtree/meta.json          {"0": {"entries": n, "rolled": r}, ...}
  memory/qtree/raw/<timestamp>.md verbatim copies of summarized material
                          (issue #9: nothing is destroyed, whatever the
                          provider does; failure entries point here)
"""

from __future__ import annotations

import asyncio
import json
import os
import re
import sys
from datetime import datetime, timezone

from .conclusions import CONCLUSION_TEXT_MAX

COMPACT_ENTRY_MAX = 4000      # Felix: max chars per summary entry
COMPACT_FANOUT = 4            # Felix: 4 entries on a level -> 1 above
# Felix R78 (2026-10-13): "we want to compress at > 50% of the models
# maximum context window" — the provider-reported usage.prompt_tokens of
# the last generation is the ONLY real signal; chars and message-count
# are retired proxies (R70/R73's numbers superseded).
COMPACT_TRIGGER_WINDOW_FRACTION = 0.5   # Felix R78: compact above 50%
COMPACT_TARGET_FRACTION = 0.25          # post-compaction landing zone
COMPACT_TRIGGER_MSGS = 2000             # backstop only (was 400)
QTREE_DIR = "memory/qtree"

_SUMMARY_PROMPT = """You maintain episodic memory for an autonomous agent. \
Summarize the material below into a dense factual digest. Rules:
- preserve: decisions, rulings, names, ids, numbers, dates, errors + fixes, \
open questions, state changes
- drop: pleasantry, restatements, tool-call scaffolding
- plain prose or tight bullet lines, no headings
- max {limit} characters — the LAST details matter most when space runs out
- write in English

After the summary, output a line exactly `===CONCLUSIONS===`, then up to 12 \
derived conclusions, one per line exactly:
CONCLUSION: <text> || KIND: peer:<username>|task|state || FROM: <short premise refs>
(KIND is peer:<username> for conclusions about a person/peer, task for \
task/project knowledge, state for system/world state; FROM references the \
material by index or a short quote fragment. Each conclusion max 400 \
characters. Omit the whole `===CONCLUSIONS===` section when nothing is \
worth deriving.)

Material:
{material}"""

_CONCL_MARKER = "===CONCLUSIONS==="
MAX_CONCLUSIONS_PER_PASS = 12
_MAX_PREMISE_LEN = 120
_MAX_PREMISES = 8
_KIND_RE = re.compile(r"^(task|state|peer:[\w.\-]{1,64})$")


def parse_generation(out: str) -> tuple[str, list[dict]]:
    """Split a compaction generation into (summary, conclusions) — R76
    two-output format. Old-format outputs (no `===CONCLUSIONS===` line)
    are fully valid: the whole text is the summary and nothing is derived
    (back-compat). Conclusions are capped (12 per pass, text <= 400 chars)
    and kinds validated (anything unrecognized becomes "task")."""
    lines = (out or "").splitlines()
    idx = next((i for i, l in enumerate(lines)
                if l.strip() == _CONCL_MARKER), None)
    if idx is None:
        return (out or "").strip(), []
    summary = "\n".join(lines[:idx]).strip()
    if not summary:
        # marker-only output: keep everything as the summary (never lose
        # material to a formatting quirk)
        return (out or "").strip(), []
    conclusions: list[dict] = []
    for line in lines[idx + 1:]:
        if not line.strip().startswith("CONCLUSION:"):
            continue
        c = _parse_conclusion_line(line)
        if c:
            conclusions.append(c)
        if len(conclusions) >= MAX_CONCLUSIONS_PER_PASS:
            break
    return summary, conclusions


def _parse_conclusion_line(line: str) -> dict | None:
    text, kind, refs = "", "task", ""
    for seg in line.split("||"):
        seg = seg.strip()
        if seg.startswith("CONCLUSION:"):
            text = seg[len("CONCLUSION:"):].strip()
        elif seg.startswith("KIND:"):
            k = seg[len("KIND:"):].strip()
            kind = k if _KIND_RE.match(k) else "task"
        elif seg.startswith("FROM:"):
            refs = seg[len("FROM:"):].strip()
    if not text:
        return None
    premises = []
    for ref in re.split(r"[,;]", refs):
        ref = ref.strip()[:_MAX_PREMISE_LEN]
        if ref and ref not in premises:
            premises.append(ref)
        if len(premises) >= _MAX_PREMISES:
            break
    return {"text": text[:CONCLUSION_TEXT_MAX], "kind": kind,
            "premises": premises}


def _now() -> datetime:
    return datetime.now(timezone.utc)


def qtree_paths(workspace: str) -> dict:
    base = os.path.join(workspace, QTREE_DIR)
    return {"base": base,
            "raw": os.path.join(base, "raw"),
            "meta": os.path.join(base, "meta.json")}


def _level_file(base: str, level: int) -> str:
    return os.path.join(base, f"L{level}.md")


def load_meta(workspace: str) -> dict:
    p = qtree_paths(workspace)
    try:
        with open(p["meta"]) as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return {}


def _save_meta(workspace: str, meta: dict) -> None:
    p = qtree_paths(workspace)
    os.makedirs(p["base"], exist_ok=True)
    with open(p["meta"], "w") as f:
        json.dump(meta, f, indent=1, sort_keys=True)


def _lvl(meta: dict, level: int) -> dict:
    """entries written at this level; rolled = already summarized upward."""
    return meta.setdefault(str(level), {"entries": 0, "rolled": 0})


def _unrolled(workspace: str, meta: dict, level: int) -> int:
    """Entries not yet summarized into the level above."""
    m = _lvl(meta, level)
    written = len(read_entries(workspace, level))
    return max(0, written - m.get("rolled", 0))


def read_entries(workspace: str, level: int) -> list[str]:
    """Entry lines of a level file, oldest first (append-only files)."""
    base = qtree_paths(workspace)["base"]
    try:
        with open(_level_file(base, level), encoding="utf-8") as f:
            return [l.rstrip("\n") for l in f if l.strip()]
    except OSError:
        return []


def _append_entry(workspace: str, level: int, line: str) -> None:
    base = qtree_paths(workspace)["base"]
    os.makedirs(base, exist_ok=True)
    with open(_level_file(base, level), "a", encoding="utf-8") as f:
        f.write(line + "\n")

def _save_raw(workspace: str, material: str, suffix: str = "") -> str:
    """Persist `material` VERBATIM under memory/qtree/raw/<timestamp>.md
    before summarizing (issue #9): whatever the provider does, the
    compacted material is never destroyed. Returns the path RELATIVE to
    the workspace, for use inside entries."""
    p = qtree_paths(workspace)
    os.makedirs(p["raw"], exist_ok=True)
    stamp = _now().strftime("%Y-%m-%d_%H-%M-%S")
    name = f"{stamp}{suffix}.md"
    n = 0
    while os.path.exists(os.path.join(p["raw"], name)):
        n += 1
        name = f"{stamp}{suffix}-{n}.md"
    with open(os.path.join(p["raw"], name), "w", encoding="utf-8") as f:
        f.write(material)
    return os.path.join(QTREE_DIR, "raw", name)


def unrolled_count(workspace: str, level: int) -> int:
    """How many NEW entries at this level await rollup (4 = roll)."""
    return _unrolled(workspace, load_meta(workspace), level)


